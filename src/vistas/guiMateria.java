    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        boolean encontrado = false;
        try{
            String idTexto= txtMateria.getText().trim();
            if(idTexto.isEmpty()){
                JOptionPane.showMessageDialog(this, "Debes buscar la materia que desea actualizar");
                return;
            }
            int idMateria = Integer.parseInt(idTexto);
            String nombre = txtNombre.getText().trim();
            if(nombre.isEmpty()){
                JOptionPane.showMessageDialog(this, "El nombre de la materia no puede estar vacio");
                return;
            }
            boolean estado = jcbEstado.isSelected();
               
            Materia materiaActualizada = new Materia(idMateria, nombre, estado);
            boolean resultado = matData.actualizarMateria(materiaActualizada);

            if (resultado) {
                JOptionPane.showMessageDialog(this, "La materia fue actualizada correctamente");
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró ninguna materia con ese ID");
            } 
        }catch (Exception e){
                JOptionPane.showMessageDialog(this, "Error al actualizar la materia: "+ e.getMessage());
        }        
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
            try {
                // TODO add your handling code here:
                
                
                if(txtMateria.getText().isEmpty()){
                    JOptionPane.showMessageDialog(this, "ingrese un id de materia");
                    return;
                }
                
                int id = Integer.parseInt(txtMateria.getText().trim());
                
                
                Materia materia = matData.buscarMateria(id);
                
                if(materia != null){
                    txtMateria.setText(String.valueOf(materia.getIdMateria()));
                    txtNombre.setText(materia.getNombre());
                    jcbEstado.setSelected(materia.isEstado());
                    
                }else{
                    JOptionPane.showMessageDialog(this, "no se encontró la materia");
                } 
            } catch (SQLException ex) {
                System.getLogger(guiMateria.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }

    }//GEN-LAST:event_btnBuscarActionPerformed

