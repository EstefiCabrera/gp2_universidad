    private void radioInscActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_radioInscActionPerformed
        if(cbAlumnos.getSelectedItem() !=null){
            entidades.Alumno aluSelec = (entidades.Alumno) cbAlumnos.getSelectedItem();
            persistencia.CursadaData cd = new persistencia.CursadaData(new persistencia.miConexion());
            
            javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jtMaterias.getModel();
            modelo.setRowCount(0);
            
            for (entidades.Materia mat : cd.materiasInscriptas(aluSelec.getIdAlumno())) {
                modelo.addRow(new Object[]{mat.getIdMateria(), mat.getNombre(), "-"});
            }
            
        }
    }//GEN-LAST:event_radioInscActionPerformed

