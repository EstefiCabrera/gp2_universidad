    private void llenarTabla() {
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(){
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;  
            }
        };
        modelo.addColumn("ID");
        modelo.addColumn("Nombre");
        modelo.addColumn("Año");
        jtMaterias.setModel(modelo);
        }
    
    private void cargarAlumnos(){
        persistencia.AlumnoData aluData= new persistencia.AlumnoData(new persistencia.miConexion());
        cbAlumnos.removeAllItems();
        for(entidades.Alumno alu: aluData.listarAlumnos()){
            cbAlumnos.addItem(alu);
        }
        
    }
    
    private void llenarTablaMaterias(){
        persistencia.MateriaData matData = new persistencia.MateriaData(new persistencia.miConexion());
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jtMaterias.getModel();
        modelo.setRowCount(0);
        for (entidades.Materia mat: matData.listarMaterias()){
            modelo.addRow(new Object[]{mat.getNombre(), mat.isEstado()});
        }
    }
