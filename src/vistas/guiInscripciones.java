    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int filaSelec = jtMaterias.getSelectedRow();
        if(cbAlumnos.getSelectedItem() != null && filaSelec !=-1){
            entidades.Alumno alu = (entidades.Alumno) cbAlumnos.getSelectedItem();
            int idMateria = (int) jtMaterias.getValueAt(filaSelec, 0);
            String nombreMat = (String) jtMaterias.getValueAt(filaSelec, 1);
            
            entidades.Materia mat = new entidades.Materia();
            mat.setIdMateria(idMateria);
            mat.setNombre(nombreMat);
            mat.setEstado(true);
            
            entidades.Cursada ins = new entidades.Cursada(alu, mat, 0.0f, 0.0f, 2026);
            persistencia.CursadaData cd= new persistencia.CursadaData(new persistencia.miConexion());
            cd.guardarInscripcion(ins);
            
            JOptionPane.showMessageDialog(this, "Alumno inscripto exitosamente en: "+nombreMat);
        }else{
            JOptionPane.showMessageDialog(this, "Por favor seleccione un alumno y materia de la lista");
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int filaSelec = jtMaterias.getSelectedRow();
        if(cbAlumnos.getSelectedItem() != null && filaSelec !=-1){
            entidades.Alumno alu = (entidades.Alumno) cbAlumnos.getSelectedItem();
            int idMateria = (int) jtMaterias.getValueAt(filaSelec, 0);
            String nombreMat = (String) jtMaterias.getValueAt(filaSelec, 1);
            
            int confirmar = JOptionPane.showConfirmDialog(this, "¿Está seguro que desea anular la inscripción?","Confirmar anulación", JOptionPane.YES_NO_OPTION);
            if(confirmar == JOptionPane.YES_OPTION){
                persistencia.CursadaData cd = new persistencia.CursadaData(new persistencia.miConexion());
                entidades.Cursada insc = new entidades.Cursada();
                insc.setAlumno(alu);
                entidades.Materia mat= new entidades.Materia();
                mat.setIdMateria(idMateria);
                insc.setMateria(mat);
                cd.anularInscripcion(insc);
            JOptionPane.showMessageDialog(this, "Inscripción anulada correctamente");
        }else{
            JOptionPane.showMessageDialog(this, "Por favor seleccione un alumno y materia de la lista");
        }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

